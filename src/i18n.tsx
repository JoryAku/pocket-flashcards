type LanguageContextValue = { language: Language; tr: (text: string) => string };
const LanguageContext = createContext<LanguageContextValue>({ language: "en", tr: (text) => text });

export function LanguageProvider({ language, children }: { language: Language; children: ReactNode }) {
  return <LanguageContext.Provider value={{ language, tr: (text) => language === "mi" ? reo[text] || text : text }}>{children}</LanguageContext.Provider>;
}

export const useLanguage = () => useContext(LanguageContext);
